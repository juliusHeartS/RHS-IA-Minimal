import { promises as fs } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { extensionRoot, loadCatalog, readJson } from './documentation.mjs';

export async function generateNavigation() {
	const { navigation, pages } = await loadCatalog();
	const actions = await readJson('manifests/actions.json');
	const spanishSections = await readJson('localization/navigation.es.json');
	const strings = { en: await readJson('localization/en.json'), es: await readJson('localization/es.json') };
	if (JSON.stringify(Object.keys(strings.en).sort()) !== JSON.stringify(Object.keys(strings.es).sort()) ||
		Object.values(strings).some(catalog => Object.values(catalog).some(value => typeof value !== 'string' || !value.trim()))) {
		throw new Error('Runtime localization catalogs must have identical nonempty string keys.');
	}
	if (JSON.stringify(Object.keys(spanishSections).sort()) !== JSON.stringify(navigation.sections.map(section => section.id).sort()) ||
		Object.values(spanishSections).some(title => typeof title !== 'string' || !title.trim())) {
		throw new Error('Spanish navigation must cover exactly the canonical sections.');
	}
	const registry = pages.map(page => ({
		id: page.id,
		fileName: page.fileName,
		sourceFileName: page.sourceFileName,
		titles: page.titles,
	}));
	const sections = navigation.sections.map(section => ({
		id: section.id,
		titles: { en: section.title, es: spanishSections[section.id] },
		pageIds: section.pages.map(page => page.id),
	}));
	const header = `/*---------------------------------------------------------------------------------------------
 *  Copyright (C) 2026 Posit Software, PBC. All rights reserved.
 *  Licensed under the Elastic License 2.0. See LICENSE.txt for license information.
 *--------------------------------------------------------------------------------------------*/

// Generated by scripts/generate-navigation.mjs. Do not edit directly.
`;
	const serialize = value => JSON.stringify(value, null, '\t').replace(/[^\x00-\x7f]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);
	await fs.writeFile(path.join(extensionRoot, 'src', 'navigation.generated.ts'), `${header}export const generatedDocumentationPages = ${serialize(registry)} as const;

export const generatedDocumentationSections = ${serialize(sections)} as const;

export const documentationStrings = ${serialize(strings)} as const;

export const documentationActions = ${serialize(actions)} as const;
`);
	console.log(`Generated bilingual registry for ${pages.length} pages.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	await generateNavigation();
}
